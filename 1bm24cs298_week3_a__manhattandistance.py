if __name__ == "__main__":
    initial_state = (1, 2, 3,
                     0, 4, 6,
                     7, 5, 8)

    print("--- Solving via Manhattan Distance Heuristic ---")
    solution = solve_a_star_manhattan(initial_state)

    if solution:
        print(f"Goal reached in {len(solution) - 1} moves.\n")
        for step in solution:
            if step.action:
                print(f"Move Blank: {step.action} (g={step.g}, h={step.h}, f={step.f})")
            else:
                print(f"Initial State (g={step.g}, h={step.h}, f={step.f})")
            print_grid(step.state)
    else:
        print("No solution found.")