import heapq

# Target Goal State
GOAL_STATE = (1, 2, 3,
              4, 5, 6,
              7, 8, 0)

class PuzzleNode:
    def __init__(self, state, parent=None, action=None, g=0, h=0):
        self.state = state
        self.parent = parent
        self.action = action
        self.g = g
        self.h = h
        self.f = g + h

    def __lt__(self, other):
        return self.f < other.f

def get_manhattan_distance(state):
    """Calculates h(n): Sum of distance of current tiles from their goal slots"""
    distance = 0
    for i in range(9):
        value = state[i]
        if value != 0:
            # Current row and column indices
            curr_row, curr_col = i // 3, i % 3
            # Target row and column indices based on Goal state
            goal_idx = GOAL_STATE.index(value)
            goal_row, goal_col = goal_idx // 3, goal_idx % 3

            distance += abs(curr_row - goal_row) + abs(curr_col - goal_col)
    return distance

def get_successors(node):
    successors = []
    state = node.state
    blank_idx = state.index(0)
    row, col = blank_idx // 3, blank_idx % 3

    moves = [(-1, 0, 'Up'), (1, 0, 'Down'), (0, -1, 'Left'), (0, 1, 'Right')]

    for dr, dc, action in moves:
        new_row, new_col = row + dr, col + dc
        if 0 <= new_row < 3 and 0 <= new_col < 3:
            new_blank_idx = new_row * 3 + new_col
            new_state = list(state)
            new_state[blank_idx], new_state[new_blank_idx] = new_state[new_blank_idx], new_state[blank_idx]
            successors.append((tuple(new_state), action))

    return successors

def print_grid(state):
    for i in range(0, 9, 3):
        print(list(state[i:i+3]))
    print()

def solve_a_star_manhattan(start_state):
    open_list = []
    closed_set = set()

    start_h = get_manhattan_distance(start_state)
    start_node = PuzzleNode(start_state, g=0, h=start_h)
    heapq.heappush(open_list, start_node)

    while open_list:
        current_node = heapq.heappop(open_list)

        if current_node.state == GOAL_STATE:
            path = []
            curr = current_node
            while curr:
                path.append(curr)
                curr = curr.parent
            return path[::-1]

        closed_set.add(current_node.state)

        for next_state, action in get_successors(current_node):
            if next_state in closed_set:
                continue

            g_cost = current_node.g + 1
            h_cost = get_manhattan_distance(next_state)
            child_node = PuzzleNode(next_state, parent=current_node, action=action, g=g_cost, h=h_cost)

            heapq.heappush(open_list, child_node)

    return None

