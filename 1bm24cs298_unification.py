def is_variable(term):
    """Variables are represented by lowercase strings (e.g., 'x', 'y')."""
    return isinstance(term, str) and term[0].islower()


def is_constant(term):
    """Constants are represented by capitalized strings (e.g., 'John', 'A')."""
    return isinstance(term, str) and term[0].isupper()


def occurs_in(var, expr):
    """Check if variable `var` occurs anywhere inside `expr`."""
    if var == expr:
        return True
    if isinstance(expr, tuple):
        return any(occurs_in(var, sub_expr) for sub_expr in expr[1:])
    return False


def apply_subst(subst, expr):
    """Apply a substitution dictionary to an expression."""
    if is_variable(expr):
        return subst.get(expr, expr)
    if isinstance(expr, tuple):
        return (expr[0],) + tuple(apply_subst(subst, arg) for arg in expr[1:])
    return expr


def unify(psi1, psi2):
    """Implementation of Unify(Psi1, Psi2) from the algorithm."""
    # Step 1: If Psi1 or Psi2 is a variable or constant
    if is_variable(psi1) or is_constant(psi1) or is_variable(psi2) or is_constant(psi2):
        # 1a) If Psi1 and Psi2 are identical, return NIL ({})
        if psi1 == psi2:
            return {}
        # 1b) Else if Psi1 is a variable
        elif is_variable(psi1):
            if occurs_in(psi1, psi2):
                return "FAILURE"
            return {psi1: psi2}
        # 1c) Else if Psi2 is a variable
        elif is_variable(psi2):
            if occurs_in(psi2, psi1):
                return "FAILURE"
            return {psi2: psi1}
        # 1d) Else return FAILURE
        else:
            return "FAILURE"

    # Step 2: If initial predicate symbols are not the same, return FAILURE
    if psi1[0] != psi2[0]:
        return "FAILURE"

    # Step 3: If Psi1 and Psi2 have a different number of arguments, return FAILURE
    if len(psi1) != len(psi2):
        return "FAILURE"

    # Step 4: Set Substitution set (SUBST) to NIL
    subst = {}

    # Step 5: Loop through each argument in Psi1 and Psi2
    for i in range(1, len(psi1)):
        # 5a) Call Unify on the ith elements
        s = unify(psi1[i], psi2[i])

        # 5b) If S = FAILURE, return FAILURE
        if s == "FAILURE":
            return "FAILURE"

        # 5c) If S != NIL, apply S to the remainder and append to SUBST
        if s != {}:
            psi1 = apply_subst(s, psi1)
            psi2 = apply_subst(s, psi2)
            subst = {k: apply_subst(s, v) for k, v in subst.items()}
            subst.update(s)

    # Step 6: Return SUBST
    return subst


def format_output(result):
    """Format the substitution dictionary to match { (val/var) } notation."""
    if result == "FAILURE":
        return "FAILURE"
    if result == {}:
        return "NIL"
    pairs = [f"({val}/{var})" for var, val in result.items()]
    return "{ " + ", ".join(pairs) + " }"


