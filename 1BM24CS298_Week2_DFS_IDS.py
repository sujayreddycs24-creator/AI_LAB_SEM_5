import copy


GOAL_STATE = [
    [1, 2, 3],
    [4, 5, 6],
    [7, 8, 0]
]

def find_blank(state):

    for r in range(3):
        for c in range(3):
            if state[r][c] == 0:
                return r, c
    return None

def get_successors(state):

    successors = []
    r, c = find_blank(state)

    # Define possible moves: Up, Down, Left, Right
    moves = {
        'Up': (r - 1, c),
        'Down': (r + 1, c),
        'Left': (r, c - 1),
        'Right': (r, c + 1)
    }

    for move, (nr, nc) in moves.items():
        if 0 <= nr < 3 and 0 <= nc < 3:
            # Create a deep copy to avoid modifying the original matrix
            new_state = copy.deepcopy(state)
            # Swap blank space with the target numbers
            new_state[r][c], new_state[nr][nc] = new_state[nr][nc], new_state[r][c]
            successors.append(new_state)

    return successors

def to_tuple(state):
    """Converts a 2D list to a tuple of tuples so it can be stored in a visited set."""
    return tuple(tuple(row) for row in state)

# =====================================================================
# 1. Depth-First Search (DFS) with a Depth Limit
# =====================================================================
def dfs(initial_state, max_depth=20):
    print("\n--- Running Depth-First Search (DFS) ---")
    # Stack stores tuples of (current_state, path_taken)
    stack = [(initial_state, [initial_state])]
    visited = set()

    while stack:
        current, path = stack.pop()

        if current == GOAL_STATE:
            return path

        current_tuple = to_tuple(current)
        if current_tuple in visited or len(path) > max_depth:
            continue

        visited.add(current_tuple)

        # Explore children
        for neighbor in get_successors(current):
            if to_tuple(neighbor) not in visited:
                stack.append((neighbor, path + [neighbor]))

    return None

# =====================================================================
# 2. Iterative Deepening Search (IDS)
# =====================================================================
def depth_limited_search(state, limit, path, visited):
    """Helper sub-routine for IDS."""
    if state == GOAL_STATE:
        return path
    if limit <= 0:
        return "CUTOFF"

    cutoff_occurred = False
    current_tuple = to_tuple(state)
    visited.add(current_tuple)

    for neighbor in get_successors(state):
        if to_tuple(neighbor) not in visited:
            # Create a temporary visited set for this branch exploration
            new_visited = visited.copy()
            result = depth_limited_search(neighbor, limit - 1, path + [neighbor], new_visited)

            if result == "CUTOFF":
                cutoff_occurred = True
            elif result is not None:
                return result

    return "CUTOFF" if cutoff_occurred else None

def ids(initial_state, max_depth_threshold=50):
    print("\n--- Running Iterative Deepening Search (IDS) ---")
    for depth in range(max_depth_threshold):
        print(f"Searching at Depth Limit: {depth}")
        visited = set()
        result = depth_limited_search(initial_state, depth, [initial_state], visited)

        if result != "CUTOFF" and result is not None:
            return result
    return None

# =====================================================================
# Execution & Testing
# =====================================================================
def print_path(path):
    if path is None:
        print("No solution found within the limits.")
        return
    print(f"Solution found in {len(path) - 1} moves!")
    for step, state in enumerate(path):
        print(f"Step {step}:")
        for row in state:
            print(row)
        print()

