import itertools

symbols=['P','Q','R']
combinations=list(itertools.product([True,False],repeat=(len(symbols))))
tt=[]

for combination in combinations:
    model=dict(zip(symbols,combination))
    tt.append(model)

def implies(p,q):
  return (p==q or q)

for i in tt:
  i['Q->P']=implies(i['Q'],i['P'])
  i['P->~Q']=implies(i['P'],not i['Q'])
  i['Q or R']=i['Q'] or i['R']
  i['KB']=i['Q->P'] and i['P->~Q'] and i['Q or R']

queries = {
    "ii) Does KB entail R?": 'R',
    "iii) Does KB entail R -> P?": ('IMPLIES', 'R', 'P'),
    "iv) Does KB entail Q -> R?": ('IMPLIES', 'Q', 'R')
}

def evaluate_query(query, row):
    if isinstance(query, str):
        return row[query]

    if query[0] == 'IMPLIES':
        return implies(query[1], query[2])

    return False
print("--- Propositional Entailment Results ---")
for description, query_expr in queries.items():
    entails = True
    for row in tt:
        if row['KB']:
            if not evaluate_query(query_expr, row):
                entails = False
                break

    print(f"{description} -> {'YES (Entails)' if entails else 'NO (Does not entail)'}")



