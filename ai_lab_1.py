import random

board=[" " for i in range(9)]
def display():
  print()
  print(board[0]+"|"+board[1]+"|"+board[2]+"")
  print("-+-+-")
  print(board[3]+"|"+board[4]+"|"+board[5]+"")
  print("-+-+-")
  print(board[6]+"|"+board[7]+"|"+board[8]+"")
  print()


def winner(symbol:str)->bool:
  if board[0]==board[1]==board[2]==symbol:
    return True
  elif board[3]==board[4]==board[5]==symbol:
    return True
  elif board[6]==board[7]==board[8]==symbol:
    return True

  elif board[0]==board[3]==board[6]==symbol:
    return True
  elif board[1]==board[4]==board[7]==symbol:
    return True
  elif board[2]==board[5]==board[8]==symbol:
    return True

  elif board[0]==board[4]==board[8]==symbol:
    return True
  elif board[2]==board[4]==board[6]==symbol:
    return True
  return False

def draw():
  return " " not in board

def play():
  print("TIC-TAC-TOE\n")
  display()
  print("\n\nX-You \nO-Computer")
  while True:
    ch=int(input("Enter your choice(1-9)")) - 1
    if ch<0 or ch>8:
      print("Invalid Move")
      continue
    if board[ch]!=" ":
      print("Invalid Move")
      continue
    board[ch]="X"

    if winner("X"):
      print("You Won!")
      display()
      break
    if draw():
      print("DRAW!!")
      display()
      break
    display()

    unused=[i for i in range(9) if board[i]==" "]
    ch=random.choice(unused)
    board[ch]="O"
    if winner("O"):
      print("Computer Won!")
      display()
      break
    if draw():
      print("DRAW!!")
      display()
      break
    display()


play()

