import heapq

# Target Goal State
GOAL_STATE = (1, 2, 3,
              8, 0, 4,
              7, 6, 5)

class PuzzleNode:
    def __init__(self, state, parent=None, action=None, g=0, h=0):
        self.state = state        # Tuple of 9 elements representing the 3x3 grid
        self.parent = parent      # Reference to parent node
        self.action = action      # Move made to reach this state
        self.g = g                # Path cost (depth)
        self.h = h                # Heuristic cost
        self.f = g + h            # Total evaluation cost

    # Custom comparison operator for the priority queue
    def __lt__(self, other):
        return self.f < other.f

def get_misplaced_tiles(state):
    """Calculates h(n): Number of misplaced tiles excluding the blank space (0)"""
    misplaced = 0
    for i in range(9):
        if state[i] != 0 and state[i] != GOAL_STATE[i]:
            misplaced += 1
    return misplaced

def get_successors(node):
    """Generates next possible valid moves (Up, Down, Left, Right)"""
    successors = []
    state = node.state
    blank_idx = state.index(0)
    row, col = blank_idx // 3, blank_idx % 3

    # Valid directional shifts (row_offset, col_offset, action_name)
    moves = [(-1, 0, 'Up'), (1, 0, 'Down'), (0, -1, 'Left'), (0, 1, 'Right')]

    for dr, dc, action in moves:
        new_row, new_col = row + dr, col + dc
        if 0 <= new_row < 3 and 0 <= new_col < 3:
            new_blank_idx = new_row * 3 + new_col
            # Create a mutable list to swap elements
            new_state = list(state)
            new_state[blank_idx], new_state[new_blank_idx] = new_state[new_blank_idx], new_state[blank_idx]
            successors.append((tuple(new_state), action))

    return successors

def print_grid(state):
    for i in range(0, 9, 3):
        print(list(state[i:i+3]))
    print()

def solve_a_star_misplaced(start_state):
    open_list = []
    # Track the lowest g cost found for any visited state
    g_score = {start_state: 0}

    start_h = get_misplaced_tiles(start_state)
    start_node = PuzzleNode(start_state, g=0, h=start_h)
    heapq.heappush(open_list, start_node)

    while open_list:
        current_node = heapq.heappop(open_list)

        # If we found a path to a state that is worse than a previously explored one, skip it
        if current_node.g > g_score.get(current_node.state, float('inf')):
            continue

        if current_node.state == GOAL_STATE:
            # Reconstruct Path
            path = []
            curr = current_node
            while curr:
                path.append(curr)
                curr = curr.parent
            return path[::-1] # Return path from Start to Goal

        for next_state, action in get_successors(current_node):
            g_cost = current_node.g + 1

            if g_cost < g_score.get(next_state, float('inf')):
                g_score[next_state] = g_cost
                h_cost = get_misplaced_tiles(next_state)
                child_node = PuzzleNode(next_state, parent=current_node, action=action, g=g_cost, h=h_cost)
                heapq.heappush(open_list, child_node)

    return None

# Example Execution
if __name__ == "__main__":
    # 0 represents the blank space
    initial_state = (1, 2, 3,
                     0, 4, 6,
                     7, 8, 5)

    print("--- Solving via Misplaced Tiles Heuristic ---")
    solution = solve_a_star_misplaced(initial_state)

    if solution:
        print(f"Goal reached in {len(solution) - 1} moves.\n")
        for step in solution:
            if step.action:
                print(f"Move Blank: {step.action} (g={step.g}, h={step.h}, f={step.f})")
            else:
                print(f"Initial State (g={step.g}, h={step.h}, f={step.f})")
            print_grid(step.state)
    else:
        print("No solution found.")